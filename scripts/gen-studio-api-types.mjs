// Generates src/studio/api-types.ts from the vendored Studio OpenAPI file (S16 plan §5, option (a): types only, no runtime dependency).
// `node scripts/gen-studio-api-types.mjs`        writes the file
// `node scripts/gen-studio-api-types.mjs --check`  exits 1 when the committed file differs from what the fixture generates
// tests/studio/api-types.test.ts runs the same comparison. Two contracts are supported side by side (E1): TARGETS lists the vendored file and the
// generated mirror of each (contract 5: 0.51.0, contract 6: 0.69.0). To add a newer Studio: add its openapi file to tests/fixtures/, add a target,
// regenerate, and re-point the operation-level test.
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

export const TARGETS = [
  { contract: 5, spec: "tests/fixtures/studio-openapi-0.51.0.json", out: "src/studio/api-types.ts" },
  { contract: 6, spec: "tests/fixtures/studio-openapi-0.69.0.json", out: "src/studio/api-types-contract6.ts" },
];
// Contract 5, kept under the old names.
export const SPEC = TARGETS[0].spec;
export const OUT = TARGETS[0].out;
export const header = (spec) => `// GENERATED by scripts/gen-studio-api-types.mjs from ${spec.split("/").pop()} (the unmodified Studio release asset). Do not edit.
// Types only: no runtime code, so nothing of this reaches main.js. Drift is caught by tests/studio/api-types.test.ts.
`;
export const HEADER = header(SPEC);

export async function generate(target = TARGETS[0]) {
  const ast = await openapiTS(new URL(`../${target.spec}`, import.meta.url));
  return header(target.spec) + astToString(ast);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  let stale = false;
  for (const target of TARGETS) {
    const text = await generate(target);
    if (process.argv.includes("--check")) {
      const have = readFileSync(target.out, "utf8");
      if (have !== text) { console.error(`${target.out} is out of date: run node scripts/gen-studio-api-types.mjs`); stale = true; }
      else console.log(`${target.out} matches ${target.spec}`);
    } else {
      writeFileSync(target.out, text);
      console.log(`wrote ${target.out} (${text.length} bytes)`);
    }
  }
  if (stale) process.exit(1);
}
