// Generates src/studio/api-types.ts from the vendored Studio OpenAPI file (S16 plan §5, option (a): types only, no runtime dependency).
// `node scripts/gen-studio-api-types.mjs`        writes the file
// `node scripts/gen-studio-api-types.mjs --check`  exits 1 when the committed file differs from what the fixture generates
// tests/studio/api-types.test.ts runs the same comparison. To move to a newer Studio: add its openapi file to tests/fixtures/, change SPEC
// below, regenerate, fix the compile errors in src/studio/ (that is the point), and re-point the operation-level test.
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

export const SPEC = "tests/fixtures/studio-openapi-0.51.0.json";
export const OUT = "src/studio/api-types.ts";
export const HEADER = `// GENERATED by scripts/gen-studio-api-types.mjs from ${SPEC.split("/").pop()} (the unmodified Studio release asset). Do not edit.
// Types only: no runtime code, so nothing of this reaches main.js. Drift is caught by tests/studio/api-types.test.ts.
`;

export async function generate() {
  const ast = await openapiTS(new URL(`../${SPEC}`, import.meta.url));
  return HEADER + astToString(ast);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const have = readFileSync(OUT, "utf8");
    if (have !== text) { console.error(`${OUT} is out of date: run node scripts/gen-studio-api-types.mjs`); process.exit(1); }
    console.log(`${OUT} matches ${SPEC}`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${text.length} bytes)`);
  }
}
